export const NIGERIAN_STATES = Object.keys(NIGERIAN_STATES_AND_CITIES);

export function getCitiesForState(stateName: string): string[] {
  if (!stateName) return [];
  // Match exact or fuzzy
  const foundKey = Object.keys(NIGERIAN_STATES_AND_CITIES).find(
    (k) => k.toLowerCase() === stateName.trim().toLowerCase() ||
           stateName.toLowerCase().includes(k.toLowerCase()) ||
           k.toLowerCase().includes(stateName.toLowerCase())
  );
  return foundKey ? NIGERIAN_STATES_AND_CITIES[foundKey] : [];
}
